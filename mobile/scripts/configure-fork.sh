#!/usr/bin/env bash
# Fork: configure a build that installs side by side with the official Immich app.
#
# Writes the git-ignored override files used by both platforms:
#   android/fork.properties       -> applicationId + launcher name (read by android/app/fork.gradle)
#   ios/Signing.local.xcconfig    -> bundle ids, app group, team and home screen name (read by ios/Signing.xcconfig)
#
# Usage:
#   scripts/configure-fork.sh --id com.example.immich.hdr --name "Immich HDR" [--team ABCDE12345]
#   scripts/configure-fork.sh --reset     # remove the overrides again
set -euo pipefail

cd "$(dirname "$0")/.."

id=""
name=""
team=""
reset=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    --id) id="$2"; shift 2 ;;
    --name) name="$2"; shift 2 ;;
    --team) team="$2"; shift 2 ;;
    --reset) reset=true; shift ;;
    -h | --help) sed -n '2,13p' "$0"; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; exit 1 ;;
  esac
done

if $reset; then
  rm -f android/fork.properties ios/Signing.local.xcconfig
  echo "Removed fork overrides."
  exit 0
fi

if [[ -z "$id" || -z "$name" ]]; then
  echo "Both --id and --name are required (see --help)." >&2
  exit 1
fi

cat > android/fork.properties <<EOF
# Generated by scripts/configure-fork.sh
IMMICH_APP_ID=$id
IMMICH_APP_NAME=$name
EOF

{
  echo "// Generated by scripts/configure-fork.sh"
  if [[ -n "$team" ]]; then
    echo "IMMICH_TEAM_ID = $team"
  fi
  echo "IMMICH_BUNDLE_ID_PROD = $id"
  echo "IMMICH_BUNDLE_ID_DEV = $id"
  echo "IMMICH_GROUP_ID = group.$id"
  echo "IMMICH_DISPLAY_NAME = $name"
} > ios/Signing.local.xcconfig

echo "Android: applicationId=$id (debug: $id.debug), name=\"$name\""
echo "iOS:     bundle id=$id (debug: $id.debug), app group=group.$id, name=\"$name\""
if [[ -z "$team" ]]; then
  echo "Note: pass --team <Apple Team ID> to sign iOS builds with your own developer account."
fi
